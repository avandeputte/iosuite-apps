import AppKit

/// Watches the general pasteboard and sends anything copied to the inbox.
/// macOS has no "clipboard changed" notification, so this polls `changeCount`, which is cheap.
@MainActor
final class ClipboardMonitor {
    private let store: NotesStore
    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int

    /// Markers that password managers and other apps put on the pasteboard to say "don't record this".
    /// See http://nspasteboard.org
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard.ignore",
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]
    private static let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "tiff", "tif", "gif", "bmp", "webp"]

    init(store: NotesStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if store.ownPasteboardChange == count { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let app = NSWorkspace.shared.frontmostApplication
        let bundleID = app?.bundleIdentifier ?? "?"
        // Which app copied and what kinds of data it put there (never the contents), to tell why something was kept or skipped.
        Log.app.info("copy from \(bundleID, privacy: .public): \(types.sorted().joined(separator: " "), privacy: .public)")
        guard types.isDisjoint(with: ClipboardMonitor.skipTypes) else { return }

        if app?.bundleIdentifier == Bundle.main.bundleIdentifier, Bundle.main.bundleIdentifier != nil { return }
        // Password managers: skipped by app as well, since not all of them mark their copies as private.
        if Prefs.ignoredAppIDs.contains(where: { $0.caseInsensitiveCompare(bundleID) == .orderedSame }) { return }
        let appName = app?.localizedName

        // Files copied in Finder: import images, record other files by path.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            for url in urls {
                if ClipboardMonitor.imageExtensions.contains(url.pathExtension.lowercased()),
                   let data = try? Data(contentsOf: url),
                   let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
                    store.addInboxImage(png: png, label: url.lastPathComponent, source: "clipboard", sourceApp: appName)
                } else {
                    store.addInboxText(url.path, sourceApp: appName)
                }
            }
            return
        }

        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            // Password managers in a browser (Proton Pass, Bitwarden…) copy from the browser and mark nothing,
            // so skip text that looks like a password.
            if Prefs.bool(Prefs.skipPasswordLikeText), ClipboardMonitor.looksLikePassword(text) {
                Log.app.info("skipped a copy that looks like a password")
                return
            }
            store.addInboxText(text, sourceApp: appName)
            return
        }

        // Images, e.g. a screenshot taken with Control-Shift-Command-4 or "Copy Image" in a browser.
        if let type = pasteboard.availableType(from: ClipboardMonitor.imageTypes),
           let data = pasteboard.data(forType: type) {
            let png = type == .png ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            if let png {
                store.addInboxImage(png: png, label: "", source: "clipboard", sourceApp: appName)
            }
        }
    }

    /// What generated passwords look like: one "word" of 10–64 characters with digits and at least three kinds of
    /// character (lowercase, uppercase, digits, symbols) that switch kind often, unlike names such as "Q3_report".
    /// Links, email addresses and file paths never count.
    static func looksLikePassword(_ text: String) -> Bool {
        let t = Array(text.trimmingCharacters(in: .whitespacesAndNewlines))
        guard (10...64).contains(t.count), !t.contains(where: \.isWhitespace) else { return false }
        let s = String(t)
        if s.contains("://") || s.hasPrefix("/") || s.hasPrefix("~") || s.hasPrefix("www.") { return false }
        if let at = s.firstIndex(of: "@"), let dot = s.lastIndex(of: "."), at < dot { return false }  // an email address
        func kind(_ c: Character) -> Int { c.isLowercase ? 0 : c.isUppercase ? 1 : c.isNumber ? 2 : 3 }
        let kinds = Set(t.map(kind))
        guard kinds.count >= 3, kinds.contains(2) else { return false }
        let switches = zip(t, t.dropFirst()).filter { kind($0) != kind($1) }.count
        return Double(switches) / Double(t.count - 1) >= 0.4
    }
}
